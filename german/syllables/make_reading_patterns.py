#!/usr/bin/env python3
"""Write reading.pat.txt: patterns that turn TeX's hyphenation points into
the syllables German reading lessons use (the Silbenmethode).

Hyphenation never splits off a single letter; reading syllables do: A-bend,
O-ma, Ra-di-o. These patterns are at level 9, above TeX's (at most 7) and the
spec's min_left/min_right (8), so they win where they apply.

    python german/syllables/make_reading_patterns.py > german/syllables/reading.pat.txt
"""

VOWELS = "aeiouäöü"
CONSONANTS = "bcdfghjklmnpqrstvwxzß"
# Vowel-consonant starts that are often a prefix before a vowel (An-ord-nung,
# Um-ar-mung, Er-in-ne-rung), where the lone vowel isn't a syllable.
PREFIXES = {"an", "ab", "um", "un", "ur", "er", "ob", "in", "ex"}


def patterns():
    out = ["% A word starting vowel-consonant-vowel opens with the lone vowel: A-bend, O-ma, I-gel."]
    out += [f".{v}9{c}{w}" for v in VOWELS for c in CONSONANTS if v + c not in PREFIXES for w in VOWELS]
    out += ["% ...also before ch, ck and sch: E-cke, A-sche."]
    out += [f".{v}9{c}" for v in VOWELS for c in ("ch", "ck", "sch")]
    out += ["% Common words whose start looks like a prefix but isn't: A-bend, A-ben-teu-er, a-ber, A-na-nas."]
    out += [".a9ben", ".a9ber.", ".a9na"]
    out += ["% Vowels in hiatus at the end of a word: Ra-di-o, Ka-ka-o, Vi-de-o, Ko-re-a."]
    out += [f"{a}9{b}." for a, b in ("io", "eo", "ao", "uo", "ia", "ea")]
    return out


if __name__ == "__main__":
    print("% Generated by german/syllables/make_reading_patterns.py; see its docstring.")
    print("\n".join(patterns()))
